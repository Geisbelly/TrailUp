"""F1 (segurança): o aluno não grava `criado_em` nem altera o próprio evento depois de gravado

## O que estava aberto

`authenticated` tem INSERT e UPDATE em `eventos_aluno`. A policy `eventos_aluno_posse_upd` só confere
`aluno_id = auth.uid()`, e o gatilho `trg_eventos_aluno_valor_do_banco` (`20261021_06`) congela no
UPDATE `classe_id`, `tipo`, `concedido_por`, `aluno_id` e `motivo` -- mas não `criado_em` nem
`referencia`. No INSERT, o `criado_em` mandado pelo cliente era aceito.

As duas colunas não são cosméticas:

- `criado_em` é o instante que `fn_fator_de_atraso` julga, o que decide se o evento cai na janela de
  um evento de turma e o dia que conta na sequência de dias. Com ele aberto, o aluno datava o evento
  para fugir do fator de atraso, entrar na janela de um evento já encerrado ou fabricar sequência.
- `referencia` é a chave da dedup de conclusão. A conclusão repetida é gravada com valor 0; trocando
  a referência dela num UPDATE (com `valor` no SET, para o gatilho de valor rodar), a dedup não acha
  a anterior e a conclusão passa a pagar de novo.

O app não precisa de nada disso: medido em 29/10 com `git grep`, o único INSERT do cliente
(`mobile/src/models/Evento.ts`, `EventoAluno.create`) manda `aluno_id`, `tipo`, `referencia` e
`valor`, e nenhum cliente (mobile ou console) faz UPDATE em `eventos_aluno`.

## O que muda

Um gatilho novo, `trg_eventos_aluno_a_trava_cliente`, BEFORE INSERT OR UPDATE, que só age quando a
escrita vem do cliente:

- INSERT: `criado_em` vira a hora do banco, e `id` sai da sequência;
- UPDATE: é recusado, com `42501` e mensagem própria.

**Por que o `id` também.** A coluna é `GENERATED BY DEFAULT`, então o cliente podia mandar o `id`. Um
`id` à frente da sequência fica lá esperando: quando a sequência chega nele, o INSERT seguinte de
QUALQUER um -- `avaliar_entrega`, presença, o app de outro aluno -- bate na PK e falha. É uma negação
de serviço global e barata (medida no e2e com `UniqueViolation` no INSERT do servidor). O cliente
não perde nada: o app não manda `id`, e o `RETURNING` devolve o que o banco deu. O custo é um valor
da sequência a mais por INSERT do cliente (o default já tirou um), o que só deixa buracos no `id`.
O servidor continua gravando o `id` que informar.

**A ordem é o ponto.** Gatilhos do mesmo evento disparam em ordem alfabética de nome, e o `a_` põe a
trava antes de `trg_eventos_aluno_valor_ins`/`_valor_upd`. Assim o atraso e a dedup do INSERT já
calculam sobre a data travada. Na ordem inversa a data gravada sairia certa e o valor, errado. O
gatilho de valor não é reescrito.

## Por que o UPDATE do cliente é recusado, e não congelado

A primeira versão desta migration congelava `criado_em` e `referencia` no UPDATE e deixava o resto
passar. Não basta. A dedup de conclusão do gatilho de valor, no UPDATE, pergunta se existe linha
ANTERIOR com a mesma chave, e "anterior" é `(criado_em, id)`. Com a trava, todo INSERT do cliente numa
mesma transação tem o mesmo `criado_em` -- então quem desempata é o `id`. E o `id` é do cliente: a
coluna é `GENERATED BY DEFAULT` (aceita valor explícito no INSERT) e `posse_upd` só confere
`aluno_id`. Medido no e2e, com a trava congelando:

- duas conclusões iguais num INSERT só (valem 10 e 0), depois `UPDATE ... SET id = -1, valor = 1` na
  repetida: as duas passam a valer 10;
- a repetida inserida com `id = -5` explícito (vale 0), depois `UPDATE ... SET valor = 1`: idem.

Congelar `id` também resolveria esses dois, mas a lista de colunas a congelar é exatamente o tipo de
coisa que se esquece na próxima coluna. Não há o que preservar: o `git grep` de 29/10 não achou
UPDATE nenhum do cliente em `eventos_aluno`. Então o cliente grava o evento e não mexe mais nele. O
upsert do PostgREST (`ON CONFLICT ... DO UPDATE`) cai no mesmo gatilho de UPDATE e também é recusado.

`42501` é o código de "sem privilégio", o mesmo da RLS: o `supabase-js` devolve erro, não lista
vazia. A mensagem diz qual regra recusou, para não ser confundida com uma policy.

O UPDATE do servidor continua passando: RPC `SECURITY DEFINER` (`current_user` é o dono),
`service_role` e `postgres`.

**A hora gravada é `now() AT TIME ZONE 'UTC'`, não `now()` puro.** `criado_em` é `timestamp without
time zone` em UTC (o default é `now()` numa sessão UTC, e todo leitor faz `AT TIME ZONE 'UTC'`). Numa
sessão UTC as duas formas dão o mesmo valor. A diferença é que o PostgREST aceita
`Prefer: timezone=...`, que vira `SET LOCAL timezone`: com `now()` puro o aluno deslocaria a data em
até 14 h pela sessão. A forma explícita grava o instante em UTC qualquer que seja o fuso.

## Por que `current_user` e não as claims

Quem é cliente se decide por `current_user IN ('authenticated', 'anon')`. As claims do JWT
(`request.jwt.claims`) **não servem**: elas continuam valendo dentro de uma RPC `SECURITY DEFINER` --
o professor que chama `avaliar_entrega` chega com `role = authenticated` nas claims do começo ao fim.
O que muda dentro da RPC é o `current_user`, que passa a ser o dono da função (`postgres`).

E o servidor grava (e corrige) `criado_em` retroativo de propósito: `avaliar_entrega` usa a data da entrega para
o atraso, e a presença usa a data da aula. Por isso essas RPCs `SECURITY DEFINER` continuam gravando o
`criado_em` que informam, e o `service_role` (a API) também -- só a escrita direta do cliente é
travada. Pelo mesmo motivo a função é `SECURITY INVOKER`: como `DEFINER`, o `current_user` dentro
dela seria sempre o dono, e a trava nunca dispararia.

`search_path = ''`: o único objeto do corpo é a sequência, e ela vem qualificada por
`pg_get_serial_sequence('public.eventos_aluno', 'id')` (que resolve a sequência da identidade).

## O GRANT de USAGE na sequência

`nextval()` roda como o cliente e **confere privilégio na sequência**; o default `IDENTITY` não
confere -- um papel só com INSERT na tabela insere pelo default e leva `permission denied for
sequence` no `nextval()` explícito. Então a trava cria uma dependência que não existia, e ela fica
explícita aqui: `GRANT USAGE ON SEQUENCE public.eventos_aluno_id_seq TO authenticated`. Em produção
(conferido em 29/10, só leitura) a sequência tem esse nome e `authenticated`/`anon` já têm USAGE --
nada caiu --, mas isso vinha das default privileges do Supabase, não de decisão registrada. O nome é
fixo no GRANT e o e2e prende que `pg_get_serial_sequence` devolve exatamente ele. `anon` não recebe:
não tem policy de INSERT.

O downgrade **não** revoga: o privilégio já existia antes desta migration, e revogar o que ela não
criou quebraria quem dependia dele.

## Downgrade

Derruba o gatilho e a função: volta ao estado de produção anterior, que é o defeito. Existe para a
migration ser reversível; não é um estado a manter.

Revision ID: 20261029_06
Revises: 20261029_05
Create Date: 2026-10-29
"""

