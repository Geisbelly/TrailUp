FUNCAO = """
CREATE OR REPLACE FUNCTION public.fn_eventos_aluno_trava_cliente()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY INVOKER
 SET search_path = ''
AS $function$
BEGIN
  -- `current_user`, nao as claims: dentro de RPC SECURITY DEFINER as claims continuam
  -- `authenticated`, e e' la que o servidor grava data retroativa de proposito.
  IF current_user IN ('authenticated', 'anon') THEN
    IF TG_OP = 'INSERT' THEN
      -- O tipo da coluna: `timestamp without time zone` em UTC, o que o default grava.
      NEW.criado_em := (now() AT TIME ZONE 'UTC');
      -- `id` a frente da sequencia colidiria com o proximo INSERT de qualquer um.
      NEW.id := nextval(pg_get_serial_sequence('public.eventos_aluno', 'id'));
    ELSE
      -- Congelar coluna nao basta: a dedup de conclusao desempata por (criado_em, id), e o
      -- cliente escolhe o id. Nenhum cliente faz UPDATE nesta tabela.
      RAISE EXCEPTION 'eventos_aluno: o cliente não altera evento depois de gravado'
        USING ERRCODE = '42501',
              HINT = 'Grave um evento novo; correção de evento é do servidor (RPC ou service_role).';
    END IF;
  END IF;
  RETURN NEW;
END;
$function$;
"""

