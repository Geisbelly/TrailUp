-- Gera o DDL do schema public (sem dado nenhum) a partir do catálogo.
-- SOMENTE LEITURA: roda no banco de origem e devolve linhas (o, k, q).
-- Salve o resultado como JSON (lista de {"o","k","q"}) e passe para carregar_schema.py.
with
pub as (select oid from pg_namespace where nspname='public'),
extobj as (select objid from pg_depend where deptype='e'),
rels as (select c.* from pg_class c where c.relnamespace=(select oid from pub) and c.oid not in (select objid from extobj)),
s as (
-- enums
select 10 o, t.typname::text k, 'CREATE TYPE public.'||quote_ident(t.typname)||' AS ENUM ('||string_agg(quote_literal(e.enumlabel), ',' order by e.enumsortorder)||');' q
from pg_type t join pg_enum e on e.enumtypid=t.oid where t.typnamespace=(select oid from pub) and t.oid not in (select objid from extobj) group by t.typname
union all
-- domains
select 11, t.typname, 'CREATE DOMAIN public.'||quote_ident(t.typname)||' AS '||format_type(t.typbasetype,t.typtypmod)||coalesce(' '||(select string_agg(pg_get_constraintdef(c.oid),' ') from pg_constraint c where c.contypid=t.oid),'')||';'
from pg_type t where t.typtype='d' and t.typnamespace=(select oid from pub) and t.oid not in (select objid from extobj)
union all
-- standalone sequences
select 20, c.relname, 'CREATE SEQUENCE IF NOT EXISTS public.'||quote_ident(c.relname)||';' from rels c where c.relkind='S'
  and not exists (select 1 from pg_depend d where d.objid=c.oid and d.deptype='i')
union all
-- tables
select 30, c.relname, 'CREATE TABLE public.'||quote_ident(c.relname)||' ('||coalesce(string_agg(
  quote_ident(a.attname)||' '||format_type(a.atttypid,a.atttypmod)
  ||case when a.attidentity='a' then ' GENERATED ALWAYS AS IDENTITY' when a.attidentity='d' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end
  ||case when a.attgenerated='s' then ' GENERATED ALWAYS AS ('||pg_get_expr(ad.adbin,ad.adrelid)||') STORED'
         when ad.adbin is not null and a.attidentity='' then ' DEFAULT '||pg_get_expr(ad.adbin,ad.adrelid) else '' end
  ||case when a.attnotnull then ' NOT NULL' else '' end, ', ' order by a.attnum),'')||');'
from rels c left join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped
left join pg_attrdef ad on ad.adrelid=c.oid and ad.adnum=a.attnum
where c.relkind in ('r','p') group by c.relname
union all
select 40+case con.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 when 'x' then 3 else 5 end, c.relname||'.'||con.conname,
 'ALTER TABLE public.'||quote_ident(c.relname)||' ADD CONSTRAINT '||quote_ident(con.conname)||' '||pg_get_constraintdef(con.oid)||';'
from pg_constraint con join rels c on c.oid=con.conrelid where con.contype in ('p','u','c','x','f')
union all
select 50, i.relname, pg_get_indexdef(i.oid)||';' from pg_index x join pg_class i on i.oid=x.indexrelid join rels c on c.oid=x.indrelid
 where not exists (select 1 from pg_constraint con where con.conindid=i.oid and con.contype in ('p','u','x'))
union all
select 60, p.proname, pg_get_functiondef(p.oid)||';' from pg_proc p where p.pronamespace=(select oid from pub) and p.oid not in (select objid from extobj) and p.prokind in ('f','p')
union all
select 61, p.proname, 'CREATE AGGREGATE?? '||p.proname from pg_proc p where p.pronamespace=(select oid from pub) and p.oid not in (select objid from extobj) and p.prokind='a'
union all
select 70, c.relname, 'CREATE OR REPLACE VIEW public.'||quote_ident(c.relname)||coalesce(' WITH ('||array_to_string(c.reloptions,', ')||')','')||' AS '||pg_get_viewdef(c.oid)
from rels c where c.relkind='v'
union all
select 71, c.relname, 'CREATE MATERIALIZED VIEW public.'||quote_ident(c.relname)||' AS '||rtrim(pg_get_viewdef(c.oid),';')||' WITH NO DATA;' from rels c where c.relkind='m'
union all
select 72, i.relname, pg_get_indexdef(i.oid)||';' from pg_index x join pg_class i on i.oid=x.indexrelid join rels c on c.oid=x.indrelid where c.relkind='m'
union all
select 80, c.relname||'.'||t.tgname, pg_get_triggerdef(t.oid)||';' from pg_trigger t join rels c on c.oid=t.tgrelid where not t.tgisinternal
union all
select 85, c.relname, 'ALTER TABLE public.'||quote_ident(c.relname)||' ENABLE ROW LEVEL SECURITY;' from rels c where c.relrowsecurity
union all
select 85, c.relname, 'ALTER TABLE public.'||quote_ident(c.relname)||' FORCE ROW LEVEL SECURITY;' from rels c where c.relforcerowsecurity
union all
select 86, p.tablename||'.'||p.policyname, 'CREATE POLICY '||quote_ident(p.policyname)||' ON public.'||quote_ident(p.tablename)||' AS '||p.permissive||' FOR '||p.cmd||' TO '||
  (select string_agg(case when r='public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r)
  ||coalesce(' USING ('||p.qual||')','')||coalesce(' WITH CHECK ('||p.with_check||')','')||';'
from pg_policies p where p.schemaname='public'
union all
-- grants on relations
select 90, c.relname, 'REVOKE ALL ON public.'||quote_ident(c.relname)||' FROM anon, authenticated, service_role, PUBLIC;' from rels c where c.relkind in ('r','p','v','m','S') and c.relacl is not null
union all
select 91, c.relname, 'GRANT '||string_agg(distinct acl.privilege_type, ', ')||' ON public.'||quote_ident(c.relname)||' TO '||case when acl.grantee=0 then 'PUBLIC' else quote_ident(pg_get_userbyid(acl.grantee)) end||';'
from rels c, aclexplode(c.relacl) acl where c.relkind in ('r','p','v','m','S') and (acl.grantee=0 or pg_get_userbyid(acl.grantee) in ('anon','authenticated','service_role'))
group by c.relname, acl.grantee
union all
select 92, p.proname, 'REVOKE ALL ON FUNCTION public.'||quote_ident(p.proname)||'('||pg_get_function_identity_arguments(p.oid)||') FROM anon, authenticated, service_role, PUBLIC;'
from pg_proc p where p.pronamespace=(select oid from pub) and p.oid not in (select objid from extobj) and p.proacl is not null and p.prokind in ('f','p')
union all
select 93, p.proname, 'GRANT EXECUTE ON FUNCTION public.'||quote_ident(p.proname)||'('||pg_get_function_identity_arguments(p.oid)||') TO '||case when acl.grantee=0 then 'PUBLIC' else quote_ident(pg_get_userbyid(acl.grantee)) end||';'
from pg_proc p, aclexplode(p.proacl) acl where p.pronamespace=(select oid from pub) and p.oid not in (select objid from extobj) and p.prokind in ('f','p') and (acl.grantee=0 or pg_get_userbyid(acl.grantee) in ('anon','authenticated','service_role'))
union all
select 95, evtname, 'CREATE EVENT TRIGGER '||quote_ident(evtname)||' ON '||evtevent||coalesce(' WHEN TAG IN ('||(select string_agg(quote_literal(x),',') from unnest(evttags) x)||')','')||' EXECUTE FUNCTION '||evtfoid::regproc::text||'();' from pg_event_trigger where evtfoid::regproc::text not like 'extensions.%' and evtfoid::regproc::text not like 'pgsodium%' and evtfoid::regproc::text not like 'graphql%'
)
select o, k, q from s order by o, k
